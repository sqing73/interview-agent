package com.interviewagent.orchestrator.entity;

import io.r2dbc.postgresql.codec.Json;
import java.time.OffsetDateTime;
import java.util.UUID;
import org.springframework.data.annotation.Id;
import org.springframework.data.relational.core.mapping.Column;
import org.springframework.data.relational.core.mapping.Table;

@Table("resumes")
public class ResumeEntity {

    @Id
    private UUID id;

    @Column("user_id")
    private UUID userId;

    @Column("file_name")
    private String fileName;

    @Column("extracted_text")
    private String extractedText;

    @Column("parsed_metadata")
    private Json parsedMetadata;

    @Column("created_at")
    private OffsetDateTime createdAt;

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public String getFileName() {
        return fileName;
    }

    public void setFileName(String fileName) {
        this.fileName = fileName;
    }

    public String getExtractedText() {
        return extractedText;
    }

    public void setExtractedText(String extractedText) {
        this.extractedText = extractedText;
    }

    public Json getParsedMetadata() {
        return parsedMetadata;
    }

    public void setParsedMetadata(Json parsedMetadata) {
        this.parsedMetadata = parsedMetadata;
    }

    public OffsetDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(OffsetDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
